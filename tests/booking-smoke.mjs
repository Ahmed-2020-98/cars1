const base='http://127.0.0.1:5188';
const day=n=>new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Riyadh',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(Date.now()+n*86400000));
const make=()=>({id:crypto.randomUUID(),token:crypto.randomUUID().replaceAll('-','')+crypto.randomUUID().replaceAll('-',''),name:'اختبار لمعة',phone:'0501234567',model:'تويوتا كامري 2024',service:'signature',vehicle:'suv',day:day(40),hour:10,total:1});
const call=async(path,data)=>{const r=await fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json','Origin':base},body:JSON.stringify(data)});return {status:r.status,data:await r.json()}};
const candidateA=make(),candidateB=make();
const results=await Promise.all([call('/api/bookings',candidateA),call('/api/bookings',candidateB)]);
assert.deepEqual(results.map(r=>r.status).sort(),[201,409],'Atomic scheduling should accept one conflicting booking');
const winnerIndex=results.findIndex(r=>r.status===201);
const winner=[candidateA,candidateB][winnerIndex];
const booked=results[winnerIndex].data.booking;
assert.equal(booked.total,530,'Server must calculate total, not trust submitted price');
const repeat=await call('/api/bookings',winner);
assert.equal(repeat.status,200);assert.equal(repeat.data.booking.reference,booked.reference);
const denied=await call('/api/bookings/manage',{reference:booked.reference,token:'0'.repeat(64)});
assert.equal(denied.status,404);
const occupied=await (await fetch(base+'/api/availability?date='+day(40)+'&service=refresh')).json();
assert.equal(occupied.slots.find(s=>s.hour===11).available,false);
const bad=await call('/api/bookings',{...make(),day:'2026-02-30'});
assert.equal(bad.status,400);
const cancelled=await call('/api/bookings/manage',{reference:booked.reference,token:winner.token,action:'cancel'});
assert.equal(cancelled.data.booking.status,'cancelled');
const available=await (await fetch(base+'/api/availability?date='+day(40)+'&service=refresh')).json();
assert.equal(available.slots.find(s=>s.hour===10).available,true);
console.log('PASS: concurrent reservations, authoritative prices, retry idempotency, token access, validation, cancellation releases slots');

